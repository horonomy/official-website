#!/usr/bin/env node
// Generate src/generated/company-metadata.ts from the pinned Horonomy company
// registry projection (AAASM-5520).
//
// WHY THIS EXISTS
// ---------------
// The site footer's Contact address and the company name were hand-typed
// literals in docusaurus.config.ts. They are owned by the Horonomy company
// metadata registry in horonomy/.github (metadata/company.yaml ->
// metadata/generated/company.json). This generator projects the pinned
// registry facts into a typed TS module the site config imports, so the
// address/name/catalog cannot drift from the company source of truth.
//
// CROSS-REPO DISTRIBUTION CONTRACT
// --------------------------------
// We PIN the registry projection to a specific horonomy/.github commit
// (REGISTRY_SOURCE below) rather than fetching mutable main at build time:
// reproducible, network-free, and fail-closed. The pinned facts are vendored in
// REGISTRY so a build needs no egress; re-pin by updating REGISTRY and
// REGISTRY_SOURCE together in one reviewed change.
//
// The generated module is deterministic and idempotent. `--check` exits non-zero
// on drift so CI blocks a stale generated module. Node stdlib only.
//
// Usage:
//   node scripts/generate-company-metadata.mjs           # write in place
//   node scripts/generate-company-metadata.mjs --check    # exit non-zero on drift

import {readFileSync, writeFileSync, mkdirSync} from 'node:fs';
import {dirname, join, relative} from 'node:path';
import {fileURLToPath} from 'node:url';

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_PATH = join(REPO_ROOT, 'src', 'generated', 'company-metadata.ts');

const REGISTRY_SOURCE = {
  repo: 'horonomy/.github',
  commit: '0bdb0e5d7b12394e2bec3099e397c9f948d7cd93',
  path: 'metadata/generated/company.json',
  blob: '911a95c0a5bf774a512a636055222cd638d4ee5e',
};

// Vendored verbatim from the pinned company.json above.
const REGISTRY = {
  company: {name: 'Horonomy', website: 'https://horonomy.dev'},
  contacts: {hello: 'hello@horonomy.dev', security: 'security@horonomy.dev'},
  products: [
    {
      id: 'ai-agent-assembly',
      name: 'AI Agent Assembly',
      website: 'https://agent-assembly.com',
      github_org: 'https://github.com/ai-agent-assembly',
      lifecycle: 'beta',
    },
    {id: 'archeweave', name: 'ArcheWeave', website: null, github_org: null, lifecycle: 'coming_soon'},
    {id: 'harbinger', name: 'Harbinger', website: null, github_org: null, lifecycle: 'coming_soon'},
  ],
};

function failClosed() {
  const emailRe = /^[^@\s]+@[^@\s]+\.[^@\s]+$/;
  if (!/^https:\/\//.test(REGISTRY.company.website)) {
    throw new Error('pinned company.website must be an https URL');
  }
  for (const [aud, addr] of Object.entries(REGISTRY.contacts)) {
    if (!emailRe.test(addr)) throw new Error(`pinned contact ${aud} is not an email`);
  }
  if (!Array.isArray(REGISTRY.products) || REGISTRY.products.length === 0) {
    throw new Error('pinned products catalog is empty');
  }
}

function render() {
  const header = [
    '// DO NOT EDIT. Generated by scripts/generate-company-metadata.mjs from the',
    '// pinned Horonomy company registry projection (AAASM-5520):',
    `//   ${REGISTRY_SOURCE.repo} @ ${REGISTRY_SOURCE.commit}`,
    `//   ${REGISTRY_SOURCE.path} (blob ${REGISTRY_SOURCE.blob})`,
    '// Re-pin and regenerate; never hand-edit. See scripts/generate-company-metadata.mjs.',
    '',
    'export type ProductLifecycle = "available" | "beta" | "coming_soon";',
    '',
    'export type CatalogProduct = {',
    '  id: string;',
    '  name: string;',
    '  website: string | null;',
    '  githubOrg: string | null;',
    '  lifecycle: ProductLifecycle;',
    '};',
    '',
  ];

  const body = [
    `export const COMPANY_NAME = ${JSON.stringify(REGISTRY.company.name)} as const;`,
    `export const COMPANY_WEBSITE = ${JSON.stringify(REGISTRY.company.website)} as const;`,
    '',
    '/** Publicly-published company contact addresses (company-owned facts only). */',
    'export const COMPANY_CONTACTS = {',
    `  hello: ${JSON.stringify(REGISTRY.contacts.hello)},`,
    `  security: ${JSON.stringify(REGISTRY.contacts.security)},`,
    '} as const;',
    '',
    '/** Product catalog — catalog-level references only; no product contact detail. */',
    'export const PRODUCTS_CATALOG: readonly CatalogProduct[] = [',
    ...REGISTRY.products.map(
      (p) =>
        `  {id: ${JSON.stringify(p.id)}, name: ${JSON.stringify(p.name)}, ` +
        `website: ${JSON.stringify(p.website)}, githubOrg: ${JSON.stringify(p.github_org)}, ` +
        `lifecycle: ${JSON.stringify(p.lifecycle)}},`,
    ),
    '] as const;',
    '',
  ];

  return header.concat(body).join('\n');
}

function main() {
  const check = process.argv.includes('--check');
  let desired;
  try {
    failClosed();
    desired = render();
  } catch (err) {
    process.stderr.write(`ERROR: company-metadata generation failed — ${err.message}\n`);
    process.exit(2);
  }

  let current = '';
  try {
    current = readFileSync(OUT_PATH, 'utf8');
  } catch {
    current = '';
  }

  if (current === desired) {
    process.stdout.write('src/generated/company-metadata.ts is up to date.\n');
    return;
  }
  if (check) {
    process.stderr.write(
      `DRIFT: ${relative(REPO_ROOT, OUT_PATH)} does not match the pinned registry.\n` +
        'Run: node scripts/generate-company-metadata.mjs\n',
    );
    process.exit(1);
  }
  mkdirSync(dirname(OUT_PATH), {recursive: true});
  writeFileSync(OUT_PATH, desired);
  process.stdout.write(`Wrote ${relative(REPO_ROOT, OUT_PATH)}.\n`);
}

main();
